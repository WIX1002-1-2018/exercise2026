package W01;

// Combining text and numbers using string concatenation.
public class W01E03 {
    public static void main(String[] args) {
        String course = "WIX1002";
        int weekNumber = 1;

        System.out.println("Course code: " + course);
        System.out.println("This is week " + weekNumber + " of the semester.");
        System.out.println(course + " - Week " + weekNumber + " - Problem Solving in Programming");
    }
}
