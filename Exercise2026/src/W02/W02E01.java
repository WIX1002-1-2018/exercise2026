package W02;

// Variables: declare, assign and initialise one variable of each common type.
public class W02E01 {
    public static void main(String[] args) {
        int weekNumber;              // declare: type and name
        weekNumber = 2;              // assign a value
        double price = 19.90;        // declare and initialise
        char grade = 'A';
        boolean isRegistered = true;

        System.out.println(weekNumber);
        System.out.println(price);
        System.out.println(grade);
        System.out.println(isRegistered);
    }
}
